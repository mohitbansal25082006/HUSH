/**
 * Hotfix signing tool.
 *
 *   npm run hotfix:keys                       create a new ECDSA P-256 key pair
 *   npm run hotfix:sign -- hotfix/filters.txt sign a filter file → hotfix/hotfix.json
 *
 * The private key lives in keys/hotfix-private.jwk (git-ignored, never ship it). The public key is
 * written to src/shared/hotfix-key.ts and bundled with the extension, which verifies every hotfix
 * before applying it. Hotfixes are pure filter data — never code — so they are allowed by the
 * Chrome Web Store remote-code policy.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { webcrypto } from 'node:crypto';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PRIVATE = join(ROOT, 'keys', 'hotfix-private.jwk');
const PUBLIC_TS = join(ROOT, 'src', 'shared', 'hotfix-key.ts');
const subtle = webcrypto.subtle;
const ALGO = { name: 'ECDSA', namedCurve: 'P-256' } as const;

async function keys() {
  if (existsSync(PRIVATE) && !process.argv.includes('--force')) {
    console.log('Key already exists (use --force to replace):', PRIVATE);
    return;
  }
  const pair = await subtle.generateKey(ALGO, true, ['sign', 'verify']);
  const priv = await subtle.exportKey('jwk', pair.privateKey);
  const pub = await subtle.exportKey('jwk', pair.publicKey);
  mkdirSync(dirname(PRIVATE), { recursive: true });
  writeFileSync(PRIVATE, JSON.stringify(priv, null, 2));
  writeFileSync(
    PUBLIC_TS,
    `/** Public key used to verify signed hotfixes (generated by scripts/hotfix.ts). */\nexport const HOTFIX_PUBLIC_KEY: JsonWebKey = ${JSON.stringify({ kty: pub.kty, crv: pub.crv, x: pub.x, y: pub.y })};\n`,
  );
  console.log('Wrote', PRIVATE, 'and', PUBLIC_TS);
}

async function sign(file: string) {
  const priv = JSON.parse(readFileSync(PRIVATE, 'utf8'));
  const key = await subtle.importKey('jwk', priv, ALGO, false, ['sign']);
  const filters = readFileSync(resolve(file), 'utf8');
  const version = Date.now();
  const payload = new TextEncoder().encode(`${version}\n${filters}`);
  const sig = await subtle.sign({ name: 'ECDSA', hash: 'SHA-256' }, key, payload);
  const out = { version, filters, signature: Buffer.from(sig).toString('base64') };
  const target = join(dirname(resolve(file)), 'hotfix.json');
  writeFileSync(target, JSON.stringify(out));
  console.log(`Signed ${filters.split('\n').filter(Boolean).length} lines → ${target} (version ${version})`);
}

const cmd = process.argv[2];
if (cmd === 'keys') await keys();
else if (cmd === 'sign') await sign(process.argv[3] ?? 'hotfix/filters.txt');
else console.log('usage: tsx scripts/hotfix.ts keys | sign <file>');
